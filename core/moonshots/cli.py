"""moonshots CLI.  Usage: bin/moonshots <command> ...

  new-venture <slug> [--name N] [--description D] [--status S]
  sync                         rescan manifests into the DB
  list                         ventures + jobs
  run <venture>/<job>          run a job now (foreground, respects approvals)
  approvals [--all]            list approvals
  request-approval <venture> <kind> <title> [--details D] [--amount USD] [--ref R]
  metric <venture> <key> <value>
  deploy <venture>             deploy per manifest `deploy:` block
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

from . import db, ventures
from .config import VENTURES, ROOT

PUBLIC_ROOT = Path(os.environ.get("MOONSHOTS_PUBLIC_ROOT", "/var/www/moon.sparelimbstudios.com/public_html"))
QUADLET_DIR = Path.home() / ".config/containers/systemd"


def deploy(slug: str):
    m = ventures.load_manifest(VENTURES / slug / "manifest.yaml")
    d = m.get("deploy") or {}
    t = d.get("type", "none")
    vdir = VENTURES / slug
    if t == "none":
        print("deploy.type is none; nothing to do")
    elif t == "static":
        src = (vdir / d.get("source", "public")).resolve()
        path = d.get("path", f"/{slug}").strip("/")
        if not path or ".." in path:
            sys.exit("deploy.path must be a non-root subpath like /arcade")
        dest = PUBLIC_ROOT / path
        if dest.exists():
            shutil.rmtree(dest)
        shutil.copytree(src, dest)
        print(f"static: {src} -> {dest}")
    elif t == "container":
        port = int(d["port"])
        if not (8101 <= port <= 8999):
            sys.exit("deploy.port must be 8101-8999 (8100 is the core)")
        cport = int(d.get("container_port", port))
        image = f"localhost/moonshots-{slug}:latest"
        ctx = vdir / d.get("context", "app")
        subprocess.run(["podman", "build", "-t", image, str(ctx)], check=True)
        QUADLET_DIR.mkdir(parents=True, exist_ok=True)
        env_file = ROOT / "secrets" / "ventures" / f"{slug}.env"
        unit = f"""# generated by moonshots deploy — do not edit
[Unit]
Description=Moonshots venture {slug}

[Container]
Image={image}
ContainerName=moonshots-{slug}
PublishPort=127.0.0.1:{port}:{cport}
{"EnvironmentFile=" + str(env_file) if env_file.exists() else ""}
Volume={ROOT}/data/ventures/{slug}:/data:Z
PodmanArgs=--memory={d.get('memory', '256m')} --cpus={d.get('cpus', '0.5')}

[Service]
Restart=always

[Install]
WantedBy=default.target
"""
        (ROOT / "data" / "ventures" / slug).mkdir(parents=True, exist_ok=True)
        (QUADLET_DIR / f"moonshots-{slug}.container").write_text(unit)
        subprocess.run(["systemctl", "--user", "daemon-reload"], check=True)
        subprocess.run(["systemctl", "--user", "restart", f"moonshots-{slug}.service"], check=True)
        print(f"container: {image} on 127.0.0.1:{port} (unit moonshots-{slug}.service)")
    else:
        sys.exit(f"unknown deploy.type {t!r}")


def main(argv=None):
    p = argparse.ArgumentParser(prog="moonshots")
    sp = p.add_subparsers(dest="cmd", required=True)
    a = sp.add_parser("new-venture"); a.add_argument("slug"); a.add_argument("--name"); a.add_argument("--description", default=""); a.add_argument("--status", default="idea")
    sp.add_parser("sync"); sp.add_parser("list")
    a = sp.add_parser("run"); a.add_argument("job_id")
    a = sp.add_parser("approvals"); a.add_argument("--all", action="store_true")
    a = sp.add_parser("request-approval"); a.add_argument("venture"); a.add_argument("kind"); a.add_argument("title")
    a.add_argument("--details", default=""); a.add_argument("--amount", type=float); a.add_argument("--ref")
    a = sp.add_parser("metric"); a.add_argument("venture"); a.add_argument("key"); a.add_argument("value", type=float)
    a = sp.add_parser("deploy"); a.add_argument("venture")
    args = p.parse_args(argv)
    db.init()

    if args.cmd == "new-venture":
        d = ventures.create(args.slug, args.name, args.description, args.status)
        ventures.sync()
        print(f"created {d}")
    elif args.cmd == "sync":
        print(f"synced {ventures.sync()} ventures")
    elif args.cmd == "list":
        for v in db.rows("SELECT slug,name,status FROM ventures ORDER BY slug"):
            print(f"{v['slug']:24} {v['status']:10} {v['name']}")
            for j in db.rows("SELECT * FROM jobs WHERE venture=?", v["slug"]):
                print(f"   - {j['name']:20} {j['schedule'] or 'manual':15} enabled={j['enabled']} approval={j['approval']}")
    elif args.cmd == "run":
        from .scheduler import Scheduler
        j = db.rows("SELECT * FROM jobs WHERE id=?", args.job_id)
        if not j:
            sys.exit("no such job (run `sync` first?)")
        Scheduler()._run(j[0], "manual:cli")
        r = db.rows("SELECT status,exit_code,output FROM job_runs WHERE job_id=? ORDER BY id DESC LIMIT 1", args.job_id)[0]
        print(r["status"], r["exit_code"]); print(r["output"] or "")
    elif args.cmd == "approvals":
        q = "SELECT * FROM approvals" + ("" if args.all else " WHERE status='pending'") + " ORDER BY id DESC"
        for r in db.rows(q):
            print(json.dumps(r, default=str))
    elif args.cmd == "request-approval":
        print(db.request_approval(args.venture, args.kind, args.title, args.details, args.amount, args.ref, "cli"))
    elif args.cmd == "metric":
        db.record_metric(args.venture, args.key, args.value); print("ok")
    elif args.cmd == "deploy":
        deploy(args.venture)


if __name__ == "__main__":
    main()
